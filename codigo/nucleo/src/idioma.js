const DICTS = { es, en };

/**
 * More texts, from outside the core (the server's own): { es: {…}, en: {…} }, merged into the dictionaries.
 * Their keys must not clash with the core's.
 */
export function addTexts(dicts) {
  for (const [l, d] of Object.entries(dicts)) {
    if (!DICTS[l]) continue;
    for (const k of Object.keys(d)) if (k in DICTS[l]) throw new Error(`text "${k}" already exists`);
    Object.assign(DICTS[l], d);
  }
}

/** Core text for `key` in the current language, with {values} filled in. */
export function tx(key, vars = {}) {
  const v = DICTS[LANG][key] ?? es[key];
  if (v == null) return key;
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

